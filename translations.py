def get_text(lang, key):
    lang = lang if lang in TRANSLATIONS else "en"
    return TRANSLATIONS[lang].get(key) or TRANSLATIONS["en"].get(key) or key


def t(key, **kw):
    """Chalu bhasha ka text, aur zaroorat ho toh usme values bhar do.

    Ek adhoora translation poora page nahi girana chahiye — placeholder galat
    ho toh bina bhare wala text hi laut jaata hai.
    """
    from flask import session
    text = get_text(session.get("lang", "en"), key)
    if not kw:
        return text
    try:
        return text.format(**kw)
    except (KeyError, IndexError, ValueError):
        return text
